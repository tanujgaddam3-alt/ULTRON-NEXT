from datetime import datetime


class ComponentCodeGenerator:
    """
    Generates initial code for new ULTRON components.
    """

    def generate(
        self,
        blueprint,
    ):

        files = []

        for file in blueprint.files:

            path = file["path"]

            purpose = file["purpose"]

            content = self._generate_file(
                blueprint.name,
                path,
                purpose,
            )

            files.append(
                {
                    "path": path,
                    "content": content,
                }
            )

        return files


