from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class TradingStrategy:
    """
    Immutable description of a moving-average trading strategy.

    A strategy is configuration only. It contains no execution logic.
    """

    name: str
    short_window: int
    long_window: int

    def __post_init__(self) -> None:
        if not isinstance(self.name, str) or not self.name.strip():
            raise ValueError("Strategy name must be a non-empty string.")

        if not isinstance(self.short_window, int):
            raise TypeError("short_window must be an integer.")

        if not isinstance(self.long_window, int):
            raise TypeError("long_window must be an integer.")

        if self.short_window < 2:
            raise ValueError("short_window must be at least 2.")

        if self.long_window <= self.short_window:
            raise ValueError(
                "long_window must be greater than short_window."
            )


@dataclass(frozen=True)
class BacktestConfig:
    """
    Configuration controlling a historical simulation.

    The defaults deliberately model a conservative research environment.
    """

    initial_capital: float = 10_000.0
    commission_rate: float = 0.001
    slippage_rate: float = 0.0005
    periods_per_year: int = 252

    def __post_init__(self) -> None:
        if self.initial_capital <= 0:
            raise ValueError("initial_capital must be positive.")

        if self.commission_rate < 0:
            raise ValueError("commission_rate cannot be negative.")

        if self.slippage_rate < 0:
            raise ValueError("slippage_rate cannot be negative.")

        if self.periods_per_year <= 0:
            raise ValueError("periods_per_year must be positive.")


@dataclass
class Trade:
    """
    Completed or active trade generated by a backtest.
    """

    entry_time: Any
    entry_price: float
    quantity: float
    exit_time: Any | None = None
    exit_price: float | None = None
    entry_cost: float = 0.0
    exit_cost: float = 0.0

    @property
    def is_closed(self) -> bool:
        return self.exit_price is not None

    @property
    def gross_pnl(self) -> float:
        if self.exit_price is None:
            return 0.0

        return (
            self.exit_price - self.entry_price
        ) * self.quantity

    @property
    def net_pnl(self) -> float:
        return (
            self.gross_pnl
            - self.entry_cost
            - self.exit_cost
        )


@dataclass
class BacktestResult:
    """
    Complete research result produced by BacktestEngine.
    """

    strategy: str
    initial_capital: float
    final_capital: float

    return_percent: float
    max_drawdown: float

    win_rate: float
    trade_count: int

    sharpe_ratio: float
    sortino_ratio: float
    calmar_ratio: float

    volatility: float
    downside_deviation: float

    exposure_percent: float
    benchmark_return_percent: float

    profit_factor: float
    average_trade_return_percent: float

    trades: list[Trade] = field(default_factory=list)

    warnings: list[str] = field(default_factory=list)

    @property
    def net_profit(self) -> float:
        return self.final_capital - self.initial_capital

    def as_dict(self) -> dict[str, Any]:
        return {
            "strategy": self.strategy,
            "initial": float(self.initial_capital),
            "final": float(self.final_capital),
            "net_profit": float(self.net_profit),
            "return_percent": float(self.return_percent),
            "max_drawdown": float(self.max_drawdown),
            "win_rate": float(self.win_rate),
            "trades": int(self.trade_count),
            "sharpe_ratio": float(self.sharpe_ratio),
            "sortino_ratio": float(self.sortino_ratio),
            "calmar_ratio": float(self.calmar_ratio),
            "volatility": float(self.volatility),
            "downside_deviation": float(self.downside_deviation),
            "exposure_percent": float(self.exposure_percent),
            "benchmark_return_percent": float(
                self.benchmark_return_percent
            ),
            "profit_factor": float(self.profit_factor),
            "average_trade_return_percent": float(
                self.average_trade_return_percent
            ),
            "warnings": list(self.warnings),
            "trade_count": int(len(self.trades)),
        }